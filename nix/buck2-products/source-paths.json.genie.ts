import { rootWorkspacePackages } from '../../package.json.genie.ts'
import { buck2SemanticFingerprint } from '../../repos/effect-utils/genie/buck2/mod.ts'
import { projectBuckProductSourcePaths } from '../../repos/effect-utils/genie/buck2/product-source-paths.ts'
import { createGenieOutput } from '../../repos/effect-utils/packages/@overeng/genie/src/runtime/core.ts'

// These are the aggregate's product entrypoints, not a handwritten source closure.
// The island is built separately from the same admitted source input.
const members = [
  'flakes/vista/cli',
  'flakes/vista/service',
  'flakes/vista/blocks',
  'flakes/vista/island',
] as const

const source = 'nix/buck2-products/source-paths.json.genie.ts'
const generator = 'vista/buck2-product-source-paths'
const schemaVersion = 1
const additionalPaths = [
  'flakes/vista/BUCK',
  'buck2/dependencies/BUCK',
  'buck2/dependencies/pnpm-lock.sha256.json',
  // The canonical dependency graph names local patches in the pnpm Buck package.
  'pnpm/BUCK',
  'pnpm/patches',
] as const

// E's supported projection retains package directories and the canonical root
// dependency supply. Unlike D's precise product slices, unrelated files inside
// those directories or dependencies may invalidate this conservative input.
const paths = [
  ...new Set([
    ...members.flatMap((member) => {
      const pkg = rootWorkspacePackages.find(
        (candidate) => candidate.meta.workspace.memberPath === member,
      )
      if (pkg === undefined) throw new Error(`No Vista source package at ${member}`)
      return projectBuckProductSourcePaths({ pkg })
    }).filter((path) => path.startsWith('repos/') === false),
    ...additionalPaths,
  ]),
].toSorted()

const packages = { 'flakes/vista': paths }
const data = {
  $comment: `Generated by ${source}; do not edit. Consumed by nix/packages.nix.`,
  packages,
  provenance: {
    generator,
    schemaVersion,
    source,
    regenerationCommand: 'genie --cwd .',
    semanticInputs: [
      source,
      'package.json.genie.ts',
      'repos/effect-utils/genie/buck2/product-source-paths.ts',
      ...rootWorkspacePackages.map((pkg) => `${pkg.meta.workspace.memberPath}/package.json.genie.ts`),
    ],
    fingerprint: buck2SemanticFingerprint({
      generator,
      schemaVersion,
      semanticData: packages,
    }),
  },
}

export default createGenieOutput({
  data,
  stringify: () => `${JSON.stringify(data, null, 2)}\n`,
})
