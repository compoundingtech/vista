const REFRESH_SHIFT_MS = 60_000

/** Harness that replaces the scene with the same data one live refresh later. */
const LiveRefreshHarness = ({ initialViewport }: { readonly initialViewport?: TraceViewport }) => {
  const [refreshes, setRefreshes] = React.useState(0)
  const scene = React.useMemo(() => {
    const model = agentTimelineFixtures['1d']
    const shift = refreshes * REFRESH_SHIFT_MS
    return projectAgentTimeline({
      ...model,
      windowStart: model.windowStart + shift,
      windowEnd: model.windowEnd + shift,
    })
  }, [refreshes])
  return (
    <div {...stylex.props(styles.viewportFrame, styles.refreshFrame)}>
      <button type="button" onClick={() => setRefreshes((count) => count + 1)}>
        Simulate live refresh ({refreshes})
      </button>
      <AgentTimeline
        scene={scene}
        {...(initialViewport === undefined ? {} : { initialViewport })}
        style={styles.refreshTrace}
      />
    </div>
  )
}

