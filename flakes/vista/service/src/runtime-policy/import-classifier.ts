import { Schema } from 'effect'

import { importRoot } from './project.ts'
import { vistaRuntimePolicy } from './project.ts'
import { ImportClassification, ImportDiagnostic, type RuntimePolicyProjection } from './schema.ts'

const decodeImportClassification = Schema.decodeUnknownSync(ImportClassification)
const decodeImportDiagnostic = Schema.decodeUnknownSync(ImportDiagnostic)

/**
 * Icon packages that authors reach for by habit. A bare import is not provided, and an esm.sh
 * copy bundles a second React; the curated Lucide set ships as `Icon` from `@vista/blocks`.
 */
const ICON_PACKAGE = /^(?:https:\/\/esm\.sh\/)?lucide-react(?:[@/?]|$)/
const ICON_GUIDANCE =
  'Icons ship with Vista: import { Icon } from \'@vista/blocks\' and render <Icon name="thumbs-up" /> (IconName lists the curated Lucide set).'

/**
 * Tests whether a module specifier names a '.provider' implementation module (with optional JS
 * extension and query/hash), which are always server-only and never client-importable.
 */
export const isVistaProviderModuleSpecifier = (specifier: string): boolean =>
  /\.provider(?:\.[cm]?[jt]sx?)?(?:[?#].*)?$/.test(specifier)

/**
 * Classifies a client import specifier into a runtime-policy category such as server-module,
 * local, provided, remote-esm, or vite-internal, using the given policy projection by default.
 */
export const classifyVistaClientImport = (
  specifier: string,
  policy: RuntimePolicyProjection = vistaRuntimePolicy(),
): ImportClassification => {
  if (isVistaProviderModuleSpecifier(specifier)) {
    return decodeImportClassification({
      _tag: 'server-module',
      specifier,
      reason: 'provider implementation modules are server-only',
    })
  }
  if (specifier.startsWith('.') || specifier.startsWith('/')) {
    return decodeImportClassification({
      _tag: 'local',
      specifier,
      reason: 'relative and absolute imports stay local to the app source',
    })
  }
  if (specifier.startsWith('node:')) {
    return decodeImportClassification({
      _tag: 'node-builtin',
      specifier,
      reason: 'Node builtins are reserved for service-side code and transform internals',
    })
  }
  if (/^(?:\/?@vite\/|\/?@react-refresh|\/?@fs\/|\/?@id\/)/.test(specifier)) {
    return decodeImportClassification({
      _tag: 'vite-internal',
      specifier,
      reason: 'Vite internal imports are generated by the service transform pipeline',
    })
  }
  const importRootAlias = policy.aliases.find((alias) => alias.specifier === importRoot(specifier))
  const exactPublicAlias = policy.aliases.some(
    (alias) => alias.public && alias.specifier === specifier,
  )
  const publicPackageImport =
    importRootAlias === undefined && policy.publicImportRoots.includes(importRoot(specifier))
  if (policy.cssImports.includes(specifier) || exactPublicAlias || publicPackageImport) {
    return decodeImportClassification({
      _tag: 'provided',
      specifier,
      reason: 'the specifier is part of the Vista public app runtime policy',
    })
  }
  if (ICON_PACKAGE.test(specifier)) {
    return decodeImportClassification({
      _tag: 'reject',
      specifier,
      reason: 'lucide-react is not provided, and an esm.sh copy would load a second React',
    })
  }
  if (policy.remoteImports.some((rule) => new RegExp(rule.pattern).test(specifier))) {
    return decodeImportClassification({
      _tag: 'remote-esm',
      specifier,
      reason: 'the specifier matches a pinned remote import escape hatch',
    })
  }
  if (specifier.startsWith('https://esm.sh/')) {
    return decodeImportClassification({
      _tag: 'remote-unpinned',
      specifier,
      reason: 'esm.sh imports must pin a package version, for example https://esm.sh/zod@3.25.76',
    })
  }
  return decodeImportClassification({
    _tag: 'reject',
    specifier,
    reason:
      'the specifier is not local, not a Vista-provided public import, and not an allowed pinned remote import',
  })
}

/**
 * Augments the import classification with an 'allowed' verdict and human-readable guidance, so
 * callers can report both the verdict and what (if anything) to do about it.
 */
export const diagnoseVistaClientImport = (
  specifier: string,
  policy: RuntimePolicyProjection = vistaRuntimePolicy(),
): ImportDiagnostic => {
  const classification = classifyVistaClientImport(specifier, policy)
  const allowed =
    classification._tag === 'local' ||
    classification._tag === 'provided' ||
    classification._tag === 'remote-esm' ||
    classification._tag === 'vite-internal'
  const guidance = (() => {
    if (allowed) return 'No action needed; this import is allowed by the Vista app runtime policy.'
    if (classification._tag === 'server-module') {
      return 'Import the adjacent *.query.ts descriptor instead of the server-only *.provider.ts implementation.'
    }
    if (classification._tag === 'remote-unpinned') {
      return 'Pin the esm.sh package URL, for example https://esm.sh/zod@3.25.76.'
    }
    if (ICON_PACKAGE.test(specifier)) return ICON_GUIDANCE
    return 'Use a Vista-provided runtime package or a pinned esm.sh URL such as https://esm.sh/zod@3.25.76.'
  })()
  return decodeImportDiagnostic({
    specifier,
    allowed,
    classification,
    message: allowed
      ? `${specifier} is allowed as ${classification._tag}`
      : `${specifier} is blocked by the Vista app runtime policy`,
    guidance,
  })
}
